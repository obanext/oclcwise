export function normalizeOclcDetailPath(path = "") {
  return String(path).replace(/\[\d+\]/g, "[]");
}

function humanizeSegment(segment) {
  const clean = segment.replace(/\[\]/g, "");
  if (termLabels[clean]) return termLabels[clean];
  return clean
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/^./, (character) => character.toUpperCase());
}

export function getOclcDetailFieldMeta(endpointKey, indexedPath) {
  const normalizedPath = normalizeOclcDetailPath(indexedPath) || "(response)";
  const siteName = exactLabels[normalizedPath]
    || normalizedPath.split(".").map(humanizeSegment).filter(Boolean).join(" – ")
    || "Response";
  const obaIst = obaIstFields.has(`${endpointKey}|${normalizedPath}`) ? "WEL" : "NIET";
  const opmerkingen = noteOverrides[`${endpointKey}|${normalizedPath}`]
    || (obaIst === "WEL"
      ? "Conceptuele tegenhanger op OBA IST; de ruwe OCLC-waarde wordt ongewijzigd weergegeven."
      : "Technisch OCLC-veld; geen zichtbare of functionele OBA IST-tegenhanger vastgesteld.");

  return { normalizedPath, siteName, obaIst, opmerkingen };
}
